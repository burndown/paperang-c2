import os
import shutil
import tempfile
import unittest

from PIL import Image, ImageChops, ImageDraw

from paperang_c2 import ipp, render


class TrimTests(unittest.TestCase):
    def test_trims_blank_tail_but_keeps_margin(self):
        im = Image.new("L", (1248, 3000), 255)
        ImageDraw.Draw(im).rectangle((100, 50, 900, 400), fill=0)
        out = ipp.trim_bottom(im)
        self.assertEqual(out.size, (1248, 401 + ipp.TRAILING_MARGIN))

    def test_blank_page_is_skipped(self):
        self.assertIsNone(ipp.trim_bottom(Image.new("L", (100, 100), 255)))

    def test_unsupported_type(self):
        d = tempfile.mkdtemp()
        path = os.path.join(d, "x.bin")
        with open(path, "wb") as f:
            f.write(b"PK\x03\x04 not a printable document")
        with self.assertRaises(RuntimeError):
            ipp.load_pages(path, "application/zip")


class CropTests(unittest.TestCase):
    def test_crops_margins_and_fills_the_width(self):
        page = Image.new("L", (1200, 1800), 255)
        ImageDraw.Draw(page).rectangle((300, 400, 900, 900), fill=0)       # 601 wide block in the middle
        out = ipp.crop_to_content(page, 1248)
        self.assertEqual(out.width, 1248)
        ink = out.point(lambda v: 255 - v).getbbox()
        self.assertLess(ink[0], 80)                                       # reaches almost to the left edge
        self.assertGreater(ink[2], 1248 - 80)                             # ... and the right edge
        self.assertLess(out.height, 1100)                                 # the empty page below/above is gone

    def test_small_content_is_not_blown_up_more_than_2x(self):
        page = Image.new("L", (1200, 1800), 255)
        ImageDraw.Draw(page).rectangle((500, 100, 600, 160), fill=0)       # a small 101x61 block
        out = ipp.crop_to_content(page, 1248)
        ink = out.point(lambda v: 255 if v < 128 else 0).getbbox()          # dark pixels only, as the printer sees them
        self.assertLessEqual(ink[2] - ink[0], 101 * 2 + 2)
        self.assertAlmostEqual((ink[0] + ink[2]) / 2, 1248 / 2, delta=3)   # centred

    def test_blank_page_is_none(self):
        self.assertIsNone(ipp.crop_to_content(Image.new("L", (400, 400), 255), 1248))


class RasterTests(unittest.TestCase):
    """Samples were generated by Ghostscript's pwgraster/urf devices, not by our own code."""
    DATA = os.path.join(os.path.dirname(__file__), "data")

    def _load(self, name):
        with open(os.path.join(self.DATA, name), "rb") as f:
            return f.read()

    def test_sniff(self):
        from paperang_c2 import raster
        self.assertEqual(raster.sniff(self._load("sample.pwg")), "image/pwg-raster")
        self.assertEqual(raster.sniff(self._load("sample.urf")), "image/urf")
        self.assertEqual(raster.sniff(b"%PDF-1.4"), "application/pdf")

    def test_pwg_and_urf_decode_to_the_same_page(self):
        from paperang_c2 import raster
        a = raster.decode(self._load("sample.pwg"))
        b = raster.decode(self._load("sample.urf"))
        self.assertEqual((len(a), len(b)), (1, 1))
        self.assertEqual(a[0].size, (1240, 1748))
        self.assertIsNone(ImageChops.difference(a[0], b[0]).getbbox())
        bbox = a[0].point(lambda v: 255 - v).getbbox()      # ink only in the drawn area
        self.assertTrue(bbox and bbox[0] > 40 and bbox[3] < 700)

    def test_truncated_data_is_an_error(self):
        from paperang_c2 import raster
        with self.assertRaises(raster.RasterError):
            raster.decode(self._load("sample.pwg")[:3000])

    def test_load_pages_ignores_generic_content_type(self):
        pages = ipp.load_pages(os.path.join(self.DATA, "sample.urf"), "application/octet-stream")
        self.assertEqual(len(pages), 1)


@unittest.skipUnless(shutil.which("pdftoppm"), "pdftoppm not installed")
class PdfTests(unittest.TestCase):
    def test_two_page_pdf(self):
        d = tempfile.mkdtemp()
        a = Image.new("RGB", (620, 877), "white")
        ImageDraw.Draw(a).text((40, 40), "page one", fill="black")
        b = Image.new("RGB", (620, 877), "white")
        ImageDraw.Draw(b).text((40, 40), "page two", fill="black")
        path = os.path.join(d, "t.pdf")
        a.save(path, save_all=True, append_images=[b])
        pages = ipp.load_pages(path, "application/pdf")
        self.assertEqual(len(pages), 2)
        fitted = render.fit_image(pages[0], 1248, "threshold")
        self.assertEqual(fitted.width, 1248)


if __name__ == "__main__":
    unittest.main()
